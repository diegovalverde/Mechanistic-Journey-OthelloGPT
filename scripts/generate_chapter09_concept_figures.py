def evidence_ladder_rule_circuit() -> None:
    steps = [
        ("Behavior", "established"),
        ("Board representation", "strong"),
        ("Semantic causality", "strong"),
        ("Layer-7 localization", "strong"),
        ("MLP7 localization", "strong"),
        ("candidate neuron population", "mixed / partial"),
        ("output-write geometry", "moderate"),
        ("small selected-neuron causality", "weak positive"),
        ("relational detector", "open"),
        ("path mediation", "open"),
        ("rescue / sufficiency", "open"),
        ("complete algorithmic circuit", "not established"),
    ]
    rows = []
    for i, (label, note) in enumerate(steps):
        y = 76 + i * 36
        rows.append(f'<rect class="box" x="230" y="{y}" width="330" height="26"/><text class="label" x="395" y="{y+18}" text-anchor="middle">{label}</text><text class="small" x="580" y="{y+18}">{note}</text>')
        if i < len(steps) - 1:
            rows.append(f'<path class="line" d="M395 {y+26} L395 {y+36}"/>')
    body = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 840 560" role="img" aria-labelledby="title desc">
<title id="title">Evidence ladder for rule circuits</title>
<desc id="desc">Evidence frontier for Chapter 9 rule-circuit hunting.</desc>
{STYLE}
<text class="title" x="42" y="44">Evidence frontier after hunting rule circuits</text>
{''.join(rows)}
<line class="frontier" x1="190" y1="253" x2="722" y2="253"/><text class="small" x="42" y="257">strong evidence frontier</text>
<line class="frontier" x1="190" y1="361" x2="722" y2="361"/><text class="small" x="42" y="365">mixed neuron frontier</text>
</svg>
'''
    write("evidence_ladder_rule_circuit.svg", body)


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    relational_capture_conditions()
    detector_vs_writer()
    distributed_hypothesis()
    evidence_ladder_rule_circuit()


if __name__ == "__main__":
    main()
