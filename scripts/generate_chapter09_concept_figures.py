def write(name: str, body: str) -> None:
    (FIG / name).write_text(body, encoding="utf-8")


def relational_capture_conditions() -> None:
    conditions = [
        ("valid capture", ["target", "opp", "opp", "mine"], "legal ray"),
        ("no terminator", ["target", "opp", "opp", "empty"], "invalid"),
        ("friendly adjacent", ["target", "mine"], "invalid"),
        ("empty adjacent", ["target", "empty"], "invalid"),
        ("broken line", ["target", "opp", "empty", "mine"], "invalid control"),
    ]
    rows = []
    for i, (name, pieces, note) in enumerate(conditions):
        y = 120 + i * 72
        rows.append(f'<text class="label" x="64" y="{y+19}">{name}</text>')
        for j, piece in enumerate(pieces):
            x = 230 + j * 78
            rows.append(f'<circle class="{piece}" cx="{x}" cy="{y}" r="19"/>')
            label = {"target": "T", "opp": "O", "mine": "M", "empty": "E"}[piece]
            rows.append(f'<text class="label" x="{x}" y="{y+5}" text-anchor="middle">{label}</text>')
            if j < len(pieces) - 1:
                rows.append(f'<line class="line" x1="{x+24}" y1="{y}" x2="{x+54}" y2="{y}"/>')
        rows.append(f'<text class="small" x="600" y="{y+5}">{note}</text>')
    body = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 820 520" role="img" aria-labelledby="title desc">
<title id="title">Relational capture conditions</title>
<desc id="desc">Matched structural ray conditions for testing candidate MLP7 neurons.</desc>
{STYLE}
<text class="title" x="42" y="48">Relational capture conditions</text>
<text class="small" x="42" y="72">Matched structural conditions used to ask whether MLP7 neurons distinguish the relational ingredients of Othello legality.</text>
{''.join(rows)}
<circle class="target" cx="94" cy="476" r="9"/><text class="small" x="110" y="480">target</text>
<circle class="opp" cx="174" cy="476" r="9"/><text class="small" x="190" y="480">opponent</text>
<circle class="mine" cx="272" cy="476" r="9"/><text class="small" x="288" y="480">friendly</text>
<circle class="empty" cx="358" cy="476" r="9"/><text class="small" x="374" y="480">empty</text>
</svg>
'''
    write("relational_capture_conditions.svg", body)


